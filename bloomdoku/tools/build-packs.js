/* Builds js/packs.js from the drawings in tools/packs/*.json:   node tools/build-packs.js
 *   helper-<kind>.json  { kind, skins: [{ id, name, es, svg }] }      the looks of one helper (64 x 64)
 *   tokens-<set>.json   { set, name, es, items: [{ name, es, svg }] } nine drawings for the cells (40 x 40)
 *   hats.json           { hats: [{ id, name, es, svg }] }             things Pua wears (in Pua's 64 x 64 box)
 * The drawings are plain SVG without ids, styles or references, so any number of copies can sit on a page; the
 * script refuses anything else. It also prints the Spanish names of the token drawings, for js/es.js. */
'use strict';
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, 'packs');
const q = (s) => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const FORBIDDEN = /<\s*(text|style|defs|linearGradient|radialGradient|filter|mask|clipPath|use|image|script|foreignObject|a)\b|\bid\s*=|href|url\(|javascript:|on[a-z]+\s*=/i;
function clean(svg, where) {
  if (typeof svg !== 'string' || !svg.trim() || FORBIDDEN.test(svg)) throw new Error(where + ': not a plain drawing');
  return svg.replace(/>\s+</g, '><').trim();
}
const out = [], es = {};
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
for (const f of files) {
  const d = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  if (d.skins) {
    if (!/^[a-z]+$/.test(d.kind) || d.skins.length !== 4) throw new Error(f + ': a helper has a kind and four looks');
    out.push('  A.helpers.' + d.kind + ' = {\n' + d.skins.map((s) => { if (!/^[a-z]+$/.test(s.id)) throw new Error(f + ': look id'); return '    ' + s.id + ': ' + q(clean(s.svg, f + ' ' + s.id)) + ','; }).join('\n') + '\n  };');
  } else if (d.items) {
    if (!/^[a-z]+$/.test(d.set) || d.items.length !== 9) throw new Error(f + ': a set has a name and nine drawings');
    out.push('  A.addSet(' + q(d.set) + ', [\n' + d.items.map((it, i) => '    ' + q(clean(it.svg, f + ' ' + (i + 1))) + ',').join('\n') + '\n  ], [' + d.items.map((it) => 'T(' + q(it.name) + ')').join(', ') + ']);');
    d.items.forEach((it) => { es[it.name] = it.es; });
  } else if (d.hats) {
    d.hats.forEach((hat) => { if (!/^[a-z]+$/.test(hat.id)) throw new Error(f + ': hat id'); out.push('  A.hats.' + hat.id + ' = ' + q(clean(hat.svg, f + ' ' + hat.id)) + ';'); });
  } else throw new Error(f + ': unknown pack');
}
const js = '/* Bloomdoku art packs: helper looks, more sets for the cells, more hats for Pua.\n' +
  ' * GENERATED by tools/build-packs.js from tools/packs/*.json. Do not edit: change the drawings there and run it again. */\n' +
  "(function () {\n  'use strict';\n  var BD = window.BD, A = BD.art;\n  function T(s) { return s; } // marks a name for translation\n\n" + out.join('\n\n') + '\n})();\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'packs.js'), js);
console.log('js/packs.js written from ' + files.length + ' packs (' + js.length + ' bytes)');
if (process.argv.includes('--es')) Object.keys(es).forEach((k) => console.log('    ' + q(k) + ': ' + q(es[k]) + ','));
