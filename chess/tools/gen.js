/* Makes puzzles from engine-vs-engine games: mate in 1, win material, mate in 2.
 *
 *   node tools/gen.js --part SEED OUT.json SECONDS   plays games for SECONDS and writes the puzzles found to OUT.json
 *   node tools/gen.js --merge DIR                    adds the puzzles of every .json in DIR to puzzles.js
 *
 * Run several --part processes at once with different seeds, then --merge. Puzzles already in puzzles.js are kept, in
 * place: the app remembers solved puzzles by their position in the list. */
const fs = require('fs'), path = require('path');
const Chess = require(path.join(__dirname, '..', 'engine.js'));
const FILE = path.join(__dirname, '..', 'puzzles.js');
const OLD = fs.existsSync(FILE) ? new Function(fs.readFileSync(FILE, 'utf8') + '; return PUZZLES;')() : [];
const WANT = { m1: 380, win: 320, m2: 300 };          // what puzzles.js should hold after a merge
const PART = { m1: 80, win: 70, m2: 100000 };         // the most one --part run keeps of each kind
const mode = process.argv[2];

if (mode === '--merge') {
  const dir = process.argv[3], seen = new Set(OLD.map((p) => Chess.key(Chess.fromFEN(p.f)))), have = { m1: 0, win: 0, m2: 0 }, fresh = [];
  for (const p of OLD) have[p.k]++;
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json')).sort()) {
    for (const p of JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'))) {
      const k = Chess.key(Chess.fromFEN(p.f));
      if (seen.has(k) || have[p.k] >= WANT[p.k]) continue;
      seen.add(k); have[p.k]++; fresh.push(p);
    }
  }
  fresh.sort((a, b) => a.r - b.r);
  const all = OLD.concat(fresh);
  fs.writeFileSync(FILE, '/* generated by tools/gen.js, do not edit */\nvar PUZZLES = ' + JSON.stringify(all).replace(/\},/g, '},\n') + ';\n');
  console.log('added ' + fresh.length + ' puzzles, ' + all.length + ' in all: ' + ['m1', 'win', 'm2'].map((k) => k + ' ' + have[k] + '/' + WANT[k]).join('  '));
  process.exit(0);
}
if (mode !== '--part') { console.log('usage: gen.js --part SEED OUT.json SECONDS | gen.js --merge DIR'); process.exit(1); }

let seed = +process.argv[3];
const OUT = process.argv[4], LIMIT = (+process.argv[5] || 300) * 1000;
const rnd = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; };
const found = { m1: [], win: [], m2: [] }, seen = new Set(OLD.map((p) => Chess.key(Chess.fromFEN(p.f))));
const need = (k) => found[k].length < PART[k];

function material(s) {
  const c = { w: 0, b: 0, wq: 0, bq: 0, n: 0 };
  for (const p of s.b) if (p) { const col = Chess.colorOf(p), t = p.toLowerCase(); c[col] += Chess.VAL[t]; c.n++; if (t === 'q') c[col + 'q']++; }
  return c;
}
function pick(s) {
  const r = Chess.rank(s, 2);
  if (rnd() < 0.1) return r[Math.floor(rnd() * r.length)].move;
  const near = r.filter((x) => x.score >= r[0].score - 50);
  return near[Math.floor(rnd() * near.length)].move;
}
function mate2(s) {
  const out = [];
  for (const m of Chess.legal(s)) {
    const u = Chess.make(s, m);
    let ok = false;
    if (Chess.inCheck(s)) {
      const rep = Chess.legal(s);
      ok = rep.length > 0 && rep.every((r) => { const v = Chess.make(s, r), f = Chess.mateMoves(s, 1).length > 0; Chess.unmake(s, r, v); return f; });
    }
    Chess.unmake(s, m, u);
    if (ok) out.push(m);
  }
  return out;
}
function scan(s) {
  const fen = Chess.toFEN(s), k = Chess.key(s);
  if (seen.has(k)) return;
  const mat = material(s);
  if (mat.n < 7 || mat.wq > 1 || mat.bq > 1) return;
  const us = s.turn, lead = mat[us] - mat[Chess.other(us)], moves = Chess.legal(s);
  if (moves.length < 8 || Chess.inCheck(s)) return;
  const m1 = Chess.mateMoves(s, 1);
  if (m1.length) {
    if (m1.length === 1 && lead < 1200 && need('m1')) { seen.add(k); found.m1.push({ f: fen, k: 'm1', r: Math.min(950, 480 + moves.length * 11) }); }
    return;
  }
  if (lead < 1200) {
    const m2 = mate2(s);
    if (m2.length === 1 && Chess.mateMoves(s, 2).length === 1) { seen.add(k); found.m2.push({ f: fen, k: 'm2', r: Math.min(1500, 1000 + moves.length * 12) }); return; }
    if (m2.length) return;
  }
  if (need('win') && Math.abs(lead) <= 400) {
    const r2 = Chess.rank(s, 2), now = Chess.evaluate(s);
    if (r2.length < 2 || r2[0].score - r2[1].score < 200) return;
    const r3 = Chess.rank(s, 3);
    if (r3.length > 1 && r3[0].score < 5000 && r3[0].score - r3[1].score >= 250 && r3[0].score - now >= 250) {
      const r4 = Chess.rank(s, 4);
      if (Chess.uci(r4[0].move) === Chess.uci(r3[0].move) && r4[0].score < 5000 && r4[0].score - r4[1].score >= 250 && r4[0].score - now >= 200) {
        seen.add(k);
        found.win.push({ f: fen, k: 'win', s: Chess.uci(r4[0].move), r: r4[0].move.cap ? 780 + moves.length * 6 : 1000 + moves.length * 5 });
      }
    }
  }
}
let games = 0;
const t0 = Date.now();
while (Date.now() - t0 < LIMIT) {
  const s = Chess.fromFEN(Chess.START);
  games++;
  for (let ply = 0; ply < 140 && Date.now() - t0 < LIMIT; ply++) {
    const st = Chess.status(s);
    if (st !== 'ok' && st !== 'check') break;
    if (ply >= 12) scan(s);
    Chess.make(s, pick(s));
  }
  if (games % 5 === 0) console.log('P ' + Math.round((Date.now() - t0) / 1000) + ' ' + games + ' ' + found.m1.length + ' ' + found.win.length + ' ' + found.m2.length);
}
fs.writeFileSync(OUT, JSON.stringify(found.m1.concat(found.win, found.m2)));
console.log('P ' + Math.round(LIMIT / 1000) + ' ' + games + ' ' + found.m1.length + ' ' + found.win.length + ' ' + found.m2.length);
